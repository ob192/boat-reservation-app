/**
 * Публічна оферта — the distance contract for SUP board rental.
 *
 * Stored as structured data (same pattern as `@/features/booking/consent-text`)
 * so that (a) the page renders it, (b) `buildOfferText()` produces a canonical
 * string for a deterministic SHA-256 hash once acceptance starts being recorded
 * in the booking payload.
 *
 * Clause numbers are NEVER written into the prose — the renderer derives them as
 * `${section.n}.${i + 1}`. Cross-references therefore name the target section by
 * its title, not by its number, so re-ordering can never falsify the document.
 *
 * Every requisite, tariff and policy constant comes from `./company`.
 */

import { COMPANY, CONTACTS, POLICY } from './company';

export interface OfferClause {
    text: string;
    items?: string[];
    tail?: string;
}

export interface OfferSection {
    /** Section number — the single source of the rendered clause numbering. */
    n: number;
    /** Anchor id used by the table of contents. */
    id: string;
    title: string;
    lead?: string;
    clauses: OfferClause[];
    /** Renders the requisites table from `./company` instead of clause bodies. */
    requisites?: boolean;
}

export interface RequisiteRow {
    label: string;
    value: string;
    href?: string;
}

