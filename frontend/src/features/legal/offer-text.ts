/**
 * Canonical text of the offer — deterministic and DOM-independent, suitable for
 * hashing. Clause numbers are derived here exactly as the page derives them.
 */
export function buildOfferText(): string {
    const o = PUBLIC_OFFER;
    const lines: string[] = [
        o.org,
        o.title,
        o.subtitle,
        `${o.id} · ${o.version} · ${o.effectiveDate}`,
        o.preamble,
    ];

    o.sections.forEach((section) => {
        lines.push(`${section.n}. ${section.title}`);
        if (section.lead) lines.push(section.lead);
        section.clauses.forEach((clause, i) => {
            lines.push(`${section.n}.${i + 1}. ${clause.text}`);
            if (clause.items) clause.items.forEach((item) => lines.push(`• ${item}`));
            if (clause.tail) lines.push(clause.tail);
        });
        if (section.requisites) {
            OFFER_REQUISITES.forEach((row) => lines.push(`${row.label}: ${row.value}`));
        }
    });

    lines.push(o.closing);
    return lines.join('\n').trim();
}
