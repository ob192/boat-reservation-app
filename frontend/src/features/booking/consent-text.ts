/** Canonical text used for the document hash — deterministic, not DOM-dependent. */
export function buildAgreementText(): string {
    const a = CONSENT_AGREEMENT;
    const lines: string[] = [a.org, a.title, a.subtitle, a.intro];
    a.clauses.forEach((c, i) => {
        lines.push(`${i + 1}. ${c.text}`);
        if (c.items) c.items.forEach((it) => lines.push(`• ${it}`));
        if (c.tail) lines.push(c.tail);
    });
    lines.push(a.closing);
    return lines.join('\n').trim();
}